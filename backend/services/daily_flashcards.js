/**
 * Daily personalised Smart Flashcards.
 *
 *  - Exactly ONE session of 5 cards per user per local day (timezone-aware), persisted in SQLite.
 *    UNIQUE(user_id, session_date) + an in-process single-flight map make concurrent/retried requests safe.
 *  - 3 cards from STRONG topics and 2 from WEAK topics, chosen from real BKT estimates (smart_flashcards.classifyTopics).
 *    When the learner has too little data the mix is adjusted transparently (labels never lie: a card is labelled
 *    strong/weak only if the topic is; otherwise learning / early_practice / new_topic) and the reasons are stored.
 *  - Cards are generated by Gemini in ONE structured call, grounded in the syllabus entry (and one reference PYQ per
 *    topic when available), then validated deterministically (schema, no PYQ impersonation, arithmetic check,
 *    relevance, duplicates vs the learner's history). If anything fails nothing is persisted - or, when possible,
 *    previously validated cards for the same topics are reused and labelled as such.
 *  - Cards are ALWAYS labelled "ai_generated_practice"; they are never presented as authentic GATE questions.
 *  - "Got it" is stored as self-assessment only: it never touches BKT.
 */
const SIZE = 5, STRONG_TARGET = 3, WEAK_TARGET = 2;
const STALE_GENERATING_MS = 3 * 60 * 1000;
const CARD_TYPES = new Set(['concept', 'formula', 'application', 'gate_style']);
const DIFFS = new Set(['easy', 'medium', 'hard']);

class FlashcardError extends Error {
  constructor(status, code, message, extra = {}) { super(message); this.status = status; this.code = code; Object.assign(this, extra); }
}

// ------------------------------------------------------------------ time
function isValidTimezone(tz) {
  if (typeof tz !== 'string' || tz.length > 64) return false;
  try { new Intl.DateTimeFormat('en-CA', { timeZone: tz }); return true; } catch (e) { return false; }
}
/** YYYY-MM-DD of `now` in the learner's timezone */
function localDate(tz, now = new Date()) {
  const parts = new Intl.DateTimeFormat('en-CA', { timeZone: tz, year: 'numeric', month: '2-digit', day: '2-digit' }).formatToParts(now);
  const g = t => parts.find(p => p.type === t).value;
  return `${g('year')}-${g('month')}-${g('day')}`;
}
function resolveTimezone(userId, requested) {
  const row = db.prepare('SELECT timezone FROM users WHERE id = ?').get(userId);
  const stored = row && isValidTimezone(row.timezone) ? row.timezone : 'UTC';
  if (requested && isValidTimezone(requested)) {
    if (requested !== stored) db.prepare('UPDATE users SET timezone = ? WHERE id = ?').run(requested, userId);
    return requested;
  }
  return stored;
}

// ------------------------------------------------------------------ helpers
const norm = t => String(t || '').toLowerCase().replace(/[^a-z0-9]+/g, ' ').trim();
const hashOf = t => crypto.createHash('sha1').update(norm(t)).digest('hex');
function seeded(str) { // tiny deterministic PRNG so the same user+day always plans identically
  let h = 2166136261; for (const c of str) { h ^= c.charCodeAt(0); h = Math.imul(h, 16777619); }
  return () => { h += 0x6D2B79F5; let t = h; t = Math.imul(t ^ (t >>> 15), t | 1); t ^= t + Math.imul(t ^ (t >>> 7), t | 61); return ((t ^ (t >>> 14)) >>> 0) / 4294967296; };
}
function jaccard(a, b) {
  const A = new Set(tokenize(a)), B = new Set(tokenize(b));
  if (!A.size || !B.size) return 0;
  let i = 0; for (const x of A) if (B.has(x)) i++;
  return i / (A.size + B.size - i);
}

// ------------------------------------------------------------------ planning (real BKT data only)
function recentTopicIds(userId, days = 3) {
  return new Set(db.prepare(`SELECT DISTINCT c.topic_id FROM fc_daily_cards c JOIN fc_daily_sessions s ON s.id = c.session_id
    WHERE c.user_id = ? AND s.session_date >= date('now', ?)`).all(userId, `-${days} day`).map(r => r.topic_id));
}

function planSession(userId, dateStr) {
  const cls = smartClassifier.classifyTopics(userId);
  const recent = recentTopicIds(userId);
  const rnd = seeded(`${userId}|${dateStr}`);
  const used = new Set(); const slots = []; const reasons = [];

  // rotation: topics not used in the last days first, then a seeded shuffle inside the best pool
  const take = (list, n, label) => {
    const fresh = list.filter(t => !used.has(t.topic_id));
    const ordered = [...fresh.filter(t => !recent.has(t.topic_id)), ...fresh.filter(t => recent.has(t.topic_id))];
    const pool = ordered.slice(0, Math.max(n * 2, n));
    const picked = [];
    while (picked.length < n && pool.length) picked.push(pool.splice(Math.floor(rnd() * pool.length), 1)[0]);
    for (const t of picked) { used.add(t.topic_id); slots.push({ topic: t, label }); }
    return picked.length;
  };
  const p = t => (t.p_know ?? 0);
  const byDesc = (a, b) => p(b) - p(a), byAsc = (a, b) => p(a) - p(b);
  const ladders = {
    strong: [['learning', [...cls.neutralTopics].sort(byDesc)], ['early_practice', [...cls.insufficientDataTopics].sort(byDesc)], ['new_topic', starter(cls.unseenTopics)]],
    weak: [['early_practice', [...cls.insufficientDataTopics].sort(byAsc)], ['learning', [...cls.neutralTopics].sort(byAsc)], ['new_topic', starter(cls.unseenTopics)]]
  };
  function starter(unseen) { // foundational, exam-relevant first
    const rootFirst = [...unseen].sort((a, b) => (b.pyq_weight || 0) - (a.pyq_weight || 0));
    return rootFirst;
  }

  for (const kind of ['strong', 'weak']) {
    const target = kind === 'strong' ? STRONG_TARGET : WEAK_TARGET;
    const have = take(kind === 'strong' ? cls.strongTopics : cls.weakTopics, target, kind);
    let missing = target - have;
    if (missing > 0) reasons.push(`Only ${have}/${target} ${kind} topics identified from your practice data`);
    for (const [label, list] of ladders[kind]) {
      if (missing <= 0) break;
      const got = take(list, missing, label);
      if (got) reasons.push(`${got} ${kind} slot(s) filled with ${label.replace('_', ' ')} topic(s): not enough evidence to call them ${kind}`);
      missing -= got;
    }
  }
  const count = l => slots.filter(s => s.label === l).length;
  return {
    slots,
    distribution: { target: { strong: STRONG_TARGET, weak: WEAK_TARGET }, actual: { strong: count('strong'), weak: count('weak'), learning: count('learning'), early_practice: count('early_practice'), new_topic: count('new_topic') }, fallbackReasons: reasons }
  };
}

// ------------------------------------------------------------------ grounding + prompt
function gatherGrounding(userId, slot, dateStr) {
  const t = slot.topic;
  const desc = syllabusTool.getTopicDescription(t.topic_id) || '';
  const kw = syllabusTool.getTopicKeywords ? syllabusTool.getTopicKeywords(t.topic_id) : '';
  const done = db.prepare("SELECT DISTINCT question_id FROM attempts WHERE user_id = ? AND question_id != ''").all(userId).map(r => r.question_id);
  const { questions } = bank.search({ topic_id: t.topic_id, hasKey: true, verifiedOnly: true }, { limit: 15 });
  const ordered = questions.sort((a, b) => (a.origin === 'official_gate' ? 0 : 1) - (b.origin === 'official_gate' ? 0 : 1) || (done.includes(a.id) ? 1 : 0) - (done.includes(b.id) ? 1 : 0));
  const ref = ordered[0] || null;
  const avoid = db.prepare('SELECT question FROM fc_daily_cards WHERE user_id = ? AND topic_id = ? ORDER BY rowid DESC LIMIT 3').all(userId, t.topic_id).map(r => r.question.slice(0, 90));
  return { desc, kw, ref, avoid };
}

const SYSTEM = `You write GATE CSE flashcards. Rules: (1) facts must agree with the supplied syllabus/reference and standard textbooks; (2) never call a card a GATE question and never mention exam years or question numbers; (3) plain text only - write math without LaTeX or backslashes (e.g. n^2, log2(n), a/b); one self-contained question per topic, answer <= 3 sentences, explanation <= 4 sentences; (4) if the answer is a number, add "calc":{"expression":"<arithmetic expression using only numbers and + - * / ^ ( )>","result":<number>} so it can be machine-checked; (5) do not repeat items in "avoid". Return JSON only: {"cards":[{"topic_id","type":"concept|formula|application|gate_style","question","answer","explanation","difficulty":"easy|medium|hard","calc"?}]} with exactly one card per requested topic.`;

// Gemini structured-output schema (constrains the shape; semantic validation still happens in validateCards)
const CARD_SCHEMA = {
  type: 'OBJECT',
  properties: { cards: { type: 'ARRAY', items: { type: 'OBJECT', properties: {
    topic_id: { type: 'STRING' }, type: { type: 'STRING', enum: ['concept', 'formula', 'application', 'gate_style'] },
    question: { type: 'STRING' }, answer: { type: 'STRING' }, explanation: { type: 'STRING' },
    difficulty: { type: 'STRING', enum: ['easy', 'medium', 'hard'] },
    calc: { type: 'OBJECT', properties: { expression: { type: 'STRING' }, result: { type: 'NUMBER' } } }
  }, required: ['topic_id', 'type', 'question', 'answer', 'explanation', 'difficulty'] } } },
  required: ['cards']
};

function buildPrompt(plan, grounding) {
  const level = { strong: 'learner is strong here: ask a harder application/GATE-style question', weak: 'learner is weak here: ask a fundamental question with a very clear explanation', learning: 'learner is mid-level: ask a moderate question', early_practice: 'learner has only 1 attempt: ask an introductory question', new_topic: 'topic not started: ask an introductory question' };
  return JSON.stringify(plan.slots.map((s, i) => {
    const g = grounding[i];
    return {
      topic_id: s.topic.topic_id, topic: s.topic.name, subject: s.topic.subject, level: level[s.label],
      syllabus: g.desc.slice(0, 320),
      reference: g.ref ? `${g.ref.question.slice(0, 220)} [official answer: ${g.ref.answer}]` : undefined,
      avoid: g.avoid.length ? g.avoid : undefined
    };
  }));
}

// ------------------------------------------------------------------ validation
/** Per-card validation. Returns { ok: [...], bad: [{ slot, reason }] }; throws only for structurally unusable output. */
function checkCards(obj, slots, groundings, history, seenHash = new Set()) {
  const cards = obj && obj.cards;
  if (!Array.isArray(cards) || cards.length !== slots.length) throw new Error(`expected exactly ${slots.length} cards`);
  const ok = [], bad = [];
  slots.forEach((slot, i) => {
    try {
      const c = cards.find(x => x && x.topic_id === slot.topic.topic_id);
      if (!c) throw new Error(`missing card for topic ${slot.topic.topic_id}`);
      for (const f of ['question', 'answer', 'explanation']) if (typeof c[f] !== 'string' || !c[f].trim()) throw new Error(`${slot.topic.topic_id}: "${f}" missing`);
      const q = c.question.trim(), a = c.answer.trim(), e = c.explanation.trim();
      if (q.length < 15 || q.length > 600) throw new Error(`${slot.topic.topic_id}: question length out of range`);
      if (a.length > 600 || e.length < 15 || e.length > 800) throw new Error(`${slot.topic.topic_id}: answer/explanation length out of range`);
      if (/\bGATE[\s-]*(19|20)\d\d\b|\bQ\.?\s*\d{1,2}\b|previous[- ]year|PYQ/i.test(`${q} ${a} ${e}`)) throw new Error(`${slot.topic.topic_id}: generated card must not reference GATE years/question numbers`);
      const type = CARD_TYPES.has(c.type) ? c.type : 'concept';
      const difficulty = DIFFS.has(c.difficulty) ? c.difficulty : (slot.label === 'strong' ? 'hard' : 'medium');
      if (c.calc && c.calc.expression !== undefined) { // deterministic arithmetic check
        let val;
        try { val = Number(math.evaluate(String(c.calc.expression))); } catch (err) { throw new Error(`${slot.topic.topic_id}: calc.expression is not evaluable`); }
        if (!Number.isFinite(val) || Math.abs(val - Number(c.calc.result)) > 1e-6 * Math.max(1, Math.abs(val))) throw new Error(`${slot.topic.topic_id}: calc does not match its stated result (${val} vs ${c.calc.result})`);
        const nums = (a.match(/-?\d+(?:\.\d+)?/g) || []).map(Number);
        if (nums.length && !nums.some(n => Math.abs(n - val) <= 0.011 * Math.max(1, Math.abs(val)))) throw new Error(`${slot.topic.topic_id}: stated answer disagrees with the checked calculation (${val})`);
      }
      const g = groundings[i];
      const vocab = new Set(tokenize(`${slot.topic.name} ${g.desc} ${g.kw}`));
      if (!tokenize(`${q} ${a}`).some(t => vocab.has(t))) throw new Error(`${slot.topic.topic_id}: card is not related to the topic`);
      const h = hashOf(q);
      if (seenHash.has(h) || history.hashes.has(h)) throw new Error(`${slot.topic.topic_id}: duplicate of an earlier card`);
      if ((history.byTopic.get(slot.topic.topic_id) || []).some(prev => jaccard(prev, q) >= 0.8)) throw new Error(`${slot.topic.topic_id}: nearly identical to a recent card`);
      seenHash.add(h);
      ok.push({ slot, type, difficulty, question: q, answer: a, explanation: e, hash: h, g });
    } catch (err) { bad.push({ slot, reason: err.message }); }
  });
  return { ok, bad };
}

/** Strict wrapper: every card must pass (used in tests / single-shot validation) */
function validateCards(obj, plan, grounding, history) {
  const { ok, bad } = checkCards(obj, plan.slots, grounding, history);
  if (bad.length) throw new Error(bad[0].reason);
  return ok;
}

function loadHistory(userId) {
  const rows = db.prepare("SELECT topic_id, question, content_hash FROM fc_daily_cards WHERE user_id = ? ORDER BY rowid DESC LIMIT 400").all(userId);
  const byTopic = new Map();
  for (const r of rows) { if (!byTopic.has(r.topic_id)) byTopic.set(r.topic_id, []); byTopic.get(r.topic_id).push(r.question); }
  return { hashes: new Set(rows.map(r => r.content_hash)), byTopic };
}

// ------------------------------------------------------------------ reuse of validated cards (fallback only)
function reuseCards(userId, plan, history) {
  const out = []; const taken = new Set();
  for (const slot of plan.slots) {
    const rows = db.prepare(`SELECT question, answer, explanation, card_type, difficulty, sources_json, content_hash FROM fc_daily_cards
      WHERE topic_id = ? AND origin = 'ai_generated_practice' ORDER BY rowid DESC LIMIT 40`).all(slot.topic.topic_id);
    const pick = rows.find(r => !history.hashes.has(r.content_hash) && !taken.has(r.content_hash));
    if (!pick) return null;
    taken.add(pick.content_hash);
    out.push({ slot, type: pick.card_type, difficulty: pick.difficulty, question: pick.question, answer: pick.answer, explanation: pick.explanation,
      hash: pick.content_hash, sources: pick.sources_json ? JSON.parse(pick.sources_json) : [] });
  }
  return out;
}

// ------------------------------------------------------------------ persistence + view
function persist(sessionId, userId, cards, generatedBy, distribution) {
  const ins = db.prepare(`INSERT INTO fc_daily_cards (id, session_id, user_id, position, topic_id, subject, card_label, mastery_at_generation,
    card_type, question, answer, explanation, difficulty, origin, sources_json, content_hash)
    VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, 'ai_generated_practice', ?, ?)`);
  const run = () => {
    cards.forEach((c, i) => {
      const sources = c.sources || [{ type: 'syllabus', topic_id: c.slot.topic.topic_id, topic: c.slot.topic.name }].concat(c.g && c.g.ref
        ? [{ type: 'reference_pyq', question_id: c.g.ref.id, year: c.g.ref.year, official: c.g.ref.origin === 'official_gate', used_as: 'grounding only' }] : []);
      ins.run(`fcc_${crypto.randomUUID()}`, sessionId, userId, i + 1, c.slot.topic.topic_id, c.slot.topic.subject, c.slot.label,
        c.slot.topic.p_know ?? null, c.type, c.question, c.answer, c.explanation, c.difficulty, JSON.stringify(sources), c.hash);
    });
    db.prepare("UPDATE fc_daily_sessions SET status = 'ready', generated_by = ?, distribution_json = ? WHERE id = ?")
      .run(generatedBy, JSON.stringify(distribution), sessionId);
  };
  db.transaction ? db.transaction(run)() : run();
}

function nextSessionAfter(tz, dateStr) {
  // first instant at which the learner's local date changes
  const base = new Date(`${dateStr}T00:00:00Z`);
  for (let h = 12; h <= 60; h += 1) { const t = new Date(base.getTime() + h * 3600 * 1000); if (localDate(tz, t) !== dateStr) return t.toISOString(); }
  return null;
}

function view(sessionId, userId) {
  const s = db.prepare('SELECT * FROM fc_daily_sessions WHERE id = ? AND user_id = ?').get(sessionId, userId);
  if (!s) return null;
  const rows = db.prepare('SELECT * FROM fc_daily_cards WHERE session_id = ? ORDER BY position').all(sessionId);
  const cards = rows.map(r => ({
    id: r.id, position: r.position, topic_id: r.topic_id, topic_name: (db.prepare('SELECT name FROM topics WHERE id = ?').get(r.topic_id) || {}).name,
    subject: r.subject, card_label: r.card_label, mastery_score: r.mastery_at_generation === null ? null : Math.round(r.mastery_at_generation * 100),
    type: r.card_type, difficulty: r.difficulty, origin: r.origin, sources: r.sources_json ? JSON.parse(r.sources_json) : [],
    question: r.question, answer: r.answer, explanation: r.explanation,
    front: r.question, back: r.explanation ? `${r.answer}\n\nWhy: ${r.explanation}` : r.answer,
    feedback: r.feedback
  }));
  const firstOpen = cards.findIndex(c => !c.feedback);
  return {
    sessionId: s.id, sessionDate: s.session_date, timezone: s.timezone, status: s.status, generatedBy: s.generated_by,
    createdAt: s.created_at, completed: s.status === 'completed', totalCards: cards.length,
    cardsAnswered: cards.filter(c => c.feedback).length, resumeIndex: firstOpen === -1 ? cards.length - 1 : firstOpen,
    distribution: s.distribution_json ? JSON.parse(s.distribution_json) : null,
    targetBreakdown: { strong: STRONG_TARGET, weak: WEAK_TARGET },
    actualBreakdown: { strong: cards.filter(c => c.card_label === 'strong').length, weak: cards.filter(c => c.card_label === 'weak').length },
    summary: s.summary_json ? JSON.parse(s.summary_json) : null,
    nextSessionAt: nextSessionAfter(s.timezone, s.session_date),
    notice: 'AI-generated practice cards grounded in the GATE CSE syllabus - not authentic GATE questions.',
    cards
  };
}

// ------------------------------------------------------------------ generation
const inflight = new Map();

async function generateSession(userId, tz, dateStr, { reuse = true } = {}) {
  const sessionId = `fcs_${crypto.randomUUID()}`;
  try {
    db.prepare("INSERT INTO fc_daily_sessions (id, user_id, session_date, timezone, status) VALUES (?, ?, ?, ?, 'generating')").run(sessionId, userId, dateStr, tz);
  } catch (e) { // another process created it first
    const ex = db.prepare('SELECT id, status FROM fc_daily_sessions WHERE user_id = ? AND session_date = ?').get(userId, dateStr);
    if (ex && ex.status !== 'generating') return ex.id;
    throw new FlashcardError(409, 'GENERATING', 'Your session is being prepared. Try again in a few seconds.');
  }
  const abandon = () => db.prepare("DELETE FROM fc_daily_sessions WHERE id = ? AND status = 'generating'").run(sessionId);
  try {
    const plan = planSession(userId, dateStr);
    if (plan.slots.length < SIZE) throw new FlashcardError(422, 'NOT_ENOUGH_TOPICS', 'Not enough syllabus topics to build a session.');
    const history = loadHistory(userId);
    const grounding = plan.slots.map(s => gatherGrounding(userId, s, dateStr));
    let cards = null, generatedBy = null, aiError = null;

    if (llm.isAvailable()) {
      try {
        const accepted = []; const seen = new Set();
        let slots = plan.slots.map((s, i) => ({ s, i })); let lastBad = null;
        for (let round = 0; round < 2 && slots.length; round++) {
          const sub = { slots: slots.map(x => x.s) }; const gsub = slots.map(x => grounding[x.i]);
          const obj = await llm.generateJSON({
            systemPrompt: SYSTEM, userPrompt: buildPrompt(sub, gsub) + (lastBad ? `\nPrevious attempt rejected: ${lastBad.map(b => b.reason).join('; ')}` : ''),
            temperature: 0.7, maxOutputTokens: 3200, responseSchema: CARD_SCHEMA, repair: false,
            agentLabel: 'Smart Flashcards', featureLabel: 'flashcard',
            validate: o => (Array.isArray(o && o.cards) ? null : 'no cards array')
          });
          const r = checkCards(obj, sub.slots, gsub, history, seen);
          r.ok.forEach(c => accepted.push({ ...c, _i: slots.find(x => x.s === c.slot).i }));
          lastBad = r.bad;
          slots = slots.filter(x => r.bad.some(b => b.slot === x.s));
          if (slots.length) console.warn(`[flashcards] ${slots.length} card(s) rejected, regenerating only those: ${r.bad.map(b => b.reason).join(' | ').slice(0, 300)}`);
        }
        if (slots.length) throw new llm.LLMError('VALIDATION', lastBad.map(b => b.reason).join('; '));
        cards = accepted.sort((a, b) => a._i - b._i);
        generatedBy = llm.modelFor('flashcard');
      } catch (e) { aiError = e; cards = null; }
    } else {
      const st = llm.status(); aiError = new llm.LLMError(st.disabledReason ? 'INVALID_KEY' : (!st.configured ? 'NO_KEY' : (st.lastError && st.lastError.code) || 'RATE_LIMIT'), 'AI service not available');
    }
    if (!cards && reuse) {
      const reused = reuseCards(userId, plan, history);
      if (reused) { cards = reused; generatedBy = 'reused_validated'; plan.distribution.fallbackReasons.push(`AI generation unavailable (${aiError && aiError.code}); reused previously validated cards not shown to you before`); }
    }
    if (!cards) {
      throw new FlashcardError(503, 'AI_UNAVAILABLE', 'Could not generate today\'s flashcards right now' + (aiError ? ` (${aiError.code}).` : '.') + ' Nothing was saved - please try again later.', { aiCode: aiError && aiError.code });
    }
    persist(sessionId, userId, cards, generatedBy, plan.distribution);
    return sessionId;
  } catch (e) { abandon(); throw e; }
}

/**
 * Today's session for the learner (creates it only if it does not exist yet).
 * @param {{tz?:string, now?:Date, reuse?:boolean}} opts  (`reuse:false` disables the validated-card fallback; used by tests)
 */
async function getToday(userId, { tz, now = new Date(), reuse = true } = {}) {
  const zone = resolveTimezone(userId, tz);
  const dateStr = localDate(zone, now);
  const read = () => db.prepare('SELECT id, status, created_at FROM fc_daily_sessions WHERE user_id = ? AND session_date = ?').get(userId, dateStr);
  let ex = read();
  if (ex && ex.status !== 'generating') return view(ex.id, userId);
  const key = `${userId}|${dateStr}`;
  if (ex && ex.status === 'generating' && !inflight.has(key)) {
    if (Date.now() - new Date(ex.created_at + 'Z').getTime() > STALE_GENERATING_MS) { db.prepare("DELETE FROM fc_daily_sessions WHERE id = ? AND status = 'generating'").run(ex.id); }
    else throw new FlashcardError(409, 'GENERATING', 'Your session is being prepared. Try again in a few seconds.');
  }
  if (!inflight.has(key)) {
    inflight.set(key, generateSession(userId, zone, dateStr, { reuse }).finally(() => inflight.delete(key)));
  }
  const id = await inflight.get(key);
  return view(id, userId);
}

// ------------------------------------------------------------------ feedback + history
function recordFeedback({ userId, sessionId, flashcardId, response }) {
  if (!['got_it', 'need_practice'].includes(response)) throw new FlashcardError(400, 'BAD_RESPONSE', "response must be 'got_it' or 'need_practice'");
  const card = db.prepare('SELECT * FROM fc_daily_cards WHERE id = ? AND session_id = ? AND user_id = ?').get(flashcardId, sessionId, userId);
  if (!card) throw new FlashcardError(404, 'NOT_FOUND', 'Flashcard not found');
  const session = db.prepare('SELECT * FROM fc_daily_sessions WHERE id = ?').get(sessionId);
  if (session.status === 'completed') throw new FlashcardError(409, 'COMPLETED', 'This session is already completed.');
  const now = new Date().toISOString();
  db.prepare('UPDATE fc_daily_cards SET feedback = ?, feedback_at = ? WHERE id = ?').run(response, now, flashcardId);   // idempotent
  const cards = db.prepare('SELECT * FROM fc_daily_cards WHERE session_id = ?').all(sessionId);
  const answered = cards.filter(c => c.feedback).length;
  let summary = null;
  if (answered === cards.length) {
    const got = cards.filter(c => c.feedback === 'got_it').length;
    const revise = [...new Set(cards.filter(c => c.feedback === 'need_practice').map(c => c.topic_id))].map(id => {
      const t = db.prepare('SELECT id, name, subject FROM topics WHERE id = ?').get(id);
      return { topic_id: t.id, topic_name: t.name, subject: t.subject, reason: 'Flagged "Need more practice"', study_url: `study.html?topic=${t.id}`, recall_url: `recall.html?topic=${t.id}` };
    });
    summary = { sessionId, completedAt: now, flashcardsCompleted: cards.length, gotItCount: got, needPracticeCount: cards.length - got,
      strongReviewed: cards.filter(c => c.card_label === 'strong').length, weakReviewed: cards.filter(c => c.card_label === 'weak').length,
      selfAssessmentOnly: true, topicsRecommended: revise };
    db.prepare("UPDATE fc_daily_sessions SET status = 'completed', completed_at = ?, summary_json = ? WHERE id = ?").run(now, JSON.stringify(summary), sessionId);
  }
  return { recorded: true, sessionCompleted: !!summary, cardsAnswered: answered, totalCards: cards.length, summary };
}

function getHistory(userId, limit = 14) {
  return db.prepare('SELECT id FROM fc_daily_sessions WHERE user_id = ? AND status != ? ORDER BY session_date DESC LIMIT ?').all(userId, 'generating', limit)
    .map(r => { const v = view(r.id, userId); return { sessionId: v.sessionId, sessionDate: v.sessionDate, status: v.status, cardsAnswered: v.cardsAnswered, totalCards: v.totalCards, summary: v.summary, actualBreakdown: v.actualBreakdown }; });
}

